#!/usr/bin/env node
// Generates docs/TOOLS.md and the tool summary of README.md from tools.json.
//
//   node scripts/generate-tools-md.mjs           rewrite both files
//   node scripts/generate-tools-md.mjs --check   exit 1 if either one is out of date
//
// No dependencies: Node.js 18 or later is enough.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const TOOLS_JSON = join(ROOT, 'tools.json')
const TOOLS_MD = join(ROOT, 'docs', 'TOOLS.md')
const README = join(ROOT, 'README.md')

const DOCS_URL = 'https://docs.maylee.app/mcp/tools'
const TOOLSET_ORDER = ['reference', 'account', 'emails', 'compose', 'config']
const PERMISSIONS = { read: 'Read', write: 'Organize and draft', send: 'Send' }
const BUDGETS = {
	send: 'hourly send budget',
	trash: 'hourly Trash and Spam budget',
	ai: 'hourly AI budget',
}
const BLOCK_START = '<!-- generated:tools-summary:start -->'
const BLOCK_END = '<!-- generated:tools-summary:end -->'
const COUNT_PATTERN = /\*\*\d+ tools?\*\* in \*\*\d+ toolsets?\*\*/g
const EXTRAS_PATTERN = /plus \d+ prompts? and \d+ reference resources?/g

const check = process.argv.includes('--check')
const data = JSON.parse(readFileSync(TOOLS_JSON, 'utf8'))

/** Text that fits in one Markdown table cell. */
function cell(text) {
	return String(text ?? '')
		.replace(/\|/g, '\\|')
		.replace(/\s*\n\s*/g, ' ')
		.trim()
}

// Only names with an underscore: a one-word name such as unsubscribe is
// also an ordinary word in the summaries.
const TOOL_NAME = new RegExp(
	`(?<![\\w\`])(${data.tools
		.map((tool) => tool.name)
		.filter((name) => name.includes('_'))
		.sort((a, b) => b.length - a.length)
		.join('|')})(?![\\w\`])`,
	'g'
)

/** Table cell text, with the tool names it mentions formatted as code. */
function prose(text) {
	return cell(text).replace(TOOL_NAME, '`$1`')
}

function plural(count, word) {
	return `${count} ${word}${count === 1 ? '' : 's'}`
}

function rank(id) {
	const index = TOOLSET_ORDER.indexOf(id)
	return index === -1 ? TOOLSET_ORDER.length : index
}

function fail(message) {
	console.error(`tools.json: ${message}`)
	process.exit(1)
}

// Toolsets in display order (reference first, as the server lists them),
// each with its tools in the order of tools.json.
const toolsets = [...data.toolsets]
	.sort((a, b) => rank(a.id) - rank(b.id))
	.map((toolset) => ({
		...toolset,
		list: data.tools.filter((tool) => tool.toolset === toolset.id),
	}))

for (const tool of data.tools) {
	if (!toolsets.some((toolset) => toolset.id === tool.toolset)) {
		fail(`tool ${tool.name} belongs to an unknown toolset "${tool.toolset}".`)
	}
	if (!PERMISSIONS[tool.permission]) {
		fail(`tool ${tool.name} has an unknown permission "${tool.permission}".`)
	}
}
for (const toolset of toolsets) {
	const listed = toolset.list.map((tool) => tool.name).join(',')
	if (listed !== toolset.tools.join(',')) {
		fail(`the tools of toolset "${toolset.id}" do not match its tool list.`)
	}
}

const total = data.tools.length

function countBy(tools, permission) {
	return tools.filter((tool) => tool.permission === permission).length
}

function anchor(title) {
	return title
		.toLowerCase()
		.replace(/[^a-z0-9 -]/g, '')
		.replace(/ /g, '-')
}

function toolUrl(tool) {
	return `${DOCS_URL}/${tool.toolset}#${tool.name}`
}

function notes(tool) {
	const out = []
	if (tool.confirm === 'always') out.push('confirm')
	if (tool.confirm === 'conditional') out.push('confirm in some cases')
	if (tool.idempotencyKey === 'required') out.push('idempotency key')
	if (tool.oauthOnly) out.push('OAuth only')
	if (tool.budget) out.push(BUDGETS[tool.budget] ?? `hourly ${tool.budget} budget`)
	return out.join(', ')
}

function permissionSummary(tools) {
	return Object.entries(PERMISSIONS)
		.map(([permission, label]) => `${countBy(tools, permission)} ${label}`)
		.join(', ')
}

function buildToolsMd() {
	const lines = [
		'<!-- Generated by scripts/generate-tools-md.mjs from tools.json. Do not edit by hand. -->',
		'',
		'# Tools',
		'',
		`Version ${data.server.version} of the Maylee MCP server exposes **${plural(total, 'tool')}** in **${plural(toolsets.length, 'toolset')}**, plus ${plural(data.prompts.length, 'prompt')} and ${plural(data.resources.length, 'reference resource')}. This page is generated from [\`tools.json\`](../tools.json), which also describes every parameter and output field. The same reference, with examples, is published at [docs.maylee.app/mcp/tools](${DOCS_URL}).`,
		'',
		'Back to the [README](../README.md).',
		'',
		'| Toolset | Tools | Read | Organize and draft | Send |',
		'| --- | ---: | ---: | ---: | ---: |',
		...toolsets.map(
			(toolset) =>
				`| [${toolset.title}](#${anchor(toolset.title)}) (\`${toolset.id}\`) | ${toolset.list.length} | ${countBy(toolset.list, 'read')} | ${countBy(toolset.list, 'write')} | ${countBy(toolset.list, 'send')} |`
		),
		`| **Total** | **${total}** | **${countBy(data.tools, 'read')}** | **${countBy(data.tools, 'write')}** | **${countBy(data.tools, 'send')}** |`,
		'',
		'## How to read the tables',
		'',
		'- **Permission** is what the connection must be allowed to do. **Read** is always granted. **Organize and draft** changes things inside Maylee (labels, drafts, rules, settings) and never sends anything. **Send** acts outside the mailbox: sending, scheduling, unsubscribing, auto-forwarding, automatic replies. A connection only lists the tools its permissions allow.',
		'- **confirm**: the tool refuses to act without `confirm: true`, which the assistant must only set after you approved that exact action. Without it, the call returns a summary to show you.',
		'- **confirm in some cases**: the same, only for the risky cases (for example more than 10 emails moved to Trash, or turning on Auto-Reply).',
		'- **idempotency key**: the call needs an `idempotencyKey`, so a retry after a timeout never sends twice. Creation tools accept an optional one.',
		'- **OAuth only**: the tool acts for a person, so it is hidden when the server is used with an API key.',
		'- **hourly budget**: the tool counts against one of the hourly safety budgets of the connection (sends and recipients, emails moved to Trash or Spam, AI generations).',
	]

	for (const toolset of toolsets) {
		lines.push(
			'',
			`## ${toolset.title}`,
			'',
			`Toolset \`${toolset.id}\`, ${plural(toolset.list.length, 'tool')}: ${prose(toolset.summary)}`,
			'',
			'| Tool | Description | Permission | Notes |',
			'| --- | --- | --- | --- |',
			...toolset.list.map(
				(tool) =>
					`| [\`${tool.name}\`](${toolUrl(tool)}) | ${cell(tool.title)} | ${PERMISSIONS[tool.permission]} | ${cell(notes(tool))} |`
			)
		)
	}

	lines.push(
		'',
		'## Prompts',
		'',
		'Guided workflows, shown in the `/` menu of clients such as Claude. They change nothing by themselves: they tell the assistant which tools to chain, and to ask you before acting.',
		'',
		'| Prompt | Description | Arguments |',
		'| --- | --- | --- |',
		...data.prompts.map(
			(prompt) =>
				`| \`${prompt.name}\` | ${prose(prompt.description)} | ${
					prompt.arguments.length
						? prompt.arguments
								.map(
									(argument) =>
										`\`${argument.name}\`${argument.required ? '' : ' (optional)'}`
								)
								.join(', ')
						: 'None'
				} |`
		),
		'',
		'## Resources',
		'',
		'The reference data used by the tools, one Markdown resource per topic. `get_reference` returns the same content.',
		'',
		'| Resource | Title | Description |',
		'| --- | --- | --- |',
		...data.resources.map(
			(resource) =>
				`| \`${resource.uri}\` | ${cell(resource.title)} | ${prose(resource.description)} |`
		),
		''
	)
	return lines.join('\n')
}

function buildReadmeBlock() {
	return [
		BLOCK_START,
		'| Toolset | Tools | What it covers |',
		'| --- | ---: | --- |',
		...toolsets.map(
			(toolset) =>
				`| [${toolset.title}](docs/TOOLS.md#${anchor(toolset.title)}) | ${toolset.list.length} | ${prose(toolset.summary)} |`
		),
		`| **Total** | **${total}** | ${permissionSummary(data.tools)} |`,
		'',
		...toolsets.flatMap((toolset) => [
			`**${toolset.title}**: ${toolset.list.map((tool) => `\`${tool.name}\``).join(', ')}`,
			'',
		]),
		BLOCK_END,
	].join('\n')
}

function updateReadme(readme) {
	const start = readme.indexOf(BLOCK_START)
	const end = readme.indexOf(BLOCK_END)
	if (start === -1 || end === -1 || end < start) {
		console.error(`README.md: missing the ${BLOCK_START} / ${BLOCK_END} markers.`)
		process.exit(1)
	}
	if (!readme.match(COUNT_PATTERN) || !readme.match(EXTRAS_PATTERN)) {
		console.error(
			'README.md: missing the "**N tools** in **N toolsets**, plus N prompts and N reference resources" sentence.'
		)
		process.exit(1)
	}
	const updated =
		readme.slice(0, start) + buildReadmeBlock() + readme.slice(end + BLOCK_END.length)
	return updated
		.replace(
			COUNT_PATTERN,
			`**${plural(total, 'tool')}** in **${plural(toolsets.length, 'toolset')}**`
		)
		.replace(
			EXTRAS_PATTERN,
			`plus ${plural(data.prompts.length, 'prompt')} and ${plural(data.resources.length, 'reference resource')}`
		)
}

const toolsMd = buildToolsMd()
const readme = readFileSync(README, 'utf8')
const nextReadme = updateReadme(readme)

if (check) {
	const problems = []
	const current = existsSync(TOOLS_MD) ? readFileSync(TOOLS_MD, 'utf8') : null
	if (current !== toolsMd) problems.push('docs/TOOLS.md is out of date.')
	if (nextReadme !== readme) problems.push('The tool summary in README.md is out of date.')
	if (problems.length) {
		console.error(
			[...problems, 'Run "node scripts/generate-tools-md.mjs" and commit the result.'].join('\n')
		)
		process.exit(1)
	}
	console.log(`docs/TOOLS.md and README.md match tools.json (${plural(total, 'tool')}).`)
} else {
	writeFileSync(TOOLS_MD, toolsMd)
	writeFileSync(README, nextReadme)
	console.log(`Wrote docs/TOOLS.md and the README tool summary (${plural(total, 'tool')}).`)
}
